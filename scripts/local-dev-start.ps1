# Local PesoWise: Supabase (Postgres + Auth + Storage + Edge Functions) + Vite frontend.
# Requires: Docker Desktop, Node.js, Supabase CLI (`npm i -g supabase` or scoop/choco).
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

Write-Host "=== 1/4 Docker ===" -ForegroundColor Cyan
docker info *> $null
if ($LASTEXITCODE -ne 0) { throw "Docker is not running. Start Docker Desktop first." }

Write-Host "=== 2/4 Supabase stack (DB migrations + local API :54321) ===" -ForegroundColor Cyan
supabase start
if ($LASTEXITCODE -ne 0) { throw "supabase start failed" }

Write-Host "=== 3/4 Write .env.local from supabase status ===" -ForegroundColor Cyan
$statusJson = supabase status -o json | ConvertFrom-Json
$apiUrl = $statusJson.API_URL
$anon = $statusJson.ANON_KEY
if (-not $apiUrl -or -not $anon) { throw "Could not read API_URL / ANON_KEY from supabase status" }

@"
# Auto-generated by scripts/local-dev-start.ps1 — local Supabase (not production)
VITE_SUPABASE_URL=$apiUrl
VITE_SUPABASE_PUBLISHABLE_KEY=$anon
"@ | Set-Content -Path (Join-Path $Root ".env.local") -Encoding utf8
Write-Host "Wrote .env.local -> $apiUrl"

Write-Host "=== 4/4 npm install (root) ===" -ForegroundColor Cyan
npm install

Write-Host @"

=== Ready ===
Terminal A (edge functions):
  cd `"$Root`"
  supabase functions serve --env-file .env.local

Terminal B (frontend):
  cd `"$Root`"
  npm run dev

Optional migration API (separate from Supabase):
  cd backend && npm install && npm run dev
  (set DATABASE_URL to local Postgres — see supabase status DB URL)

Studio: $($statusJson.STUDIO_URL)
"@ -ForegroundColor Green
