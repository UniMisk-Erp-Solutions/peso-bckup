#!/usr/bin/env node
/**
 * Generates tdl/PesoWise-Tally.tdl.
 *
 * All four reports show the SAME five columns as the workbook "Import Sheet" (aggregated by the shared engine):
 *   Voucher Date (Tally) | Expense Ledger | Employe Ledger | Voucher ID | Total
 * Data tokens in PWTCELLS: 1 ISO date (sort only) | 2 display date | 3 expense ledger | 4 employee ledger | 5 voucher id | 6 total text | 7 total number
 *
 * Lessons carried over from the previous integration:
 *  - never evaluate JSON at report time (TallyPrime crashed with c0000005): only a flat pipe string is read;
 *  - do not scope Ledger collections with `Child Of` (TallyPrime 7 returned zero rows): filter a global Ledger collection by report UDF;
 *  - collection names used inside $$CollCount:/$$CollNumTotal: must not contain spaces.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const repo = join(root, "..", "..");
const esbuild = createRequire(join(repo, "package.json"))("esbuild");
mkdirSync(join(root, "dist"), { recursive: true });
const tmp = join(root, "dist", "_cols.cjs");
await esbuild.build({
  entryPoints: [join(repo, "supabase/functions/_shared/pwt/reportRows.ts")],
  bundle: true, platform: "node", format: "cjs", outfile: tmp, logLevel: "error",
});
const { FIVE_COLUMNS } = createRequire(import.meta.url)(tmp);
if (FIVE_COLUMNS.length !== 5) throw new Error("expected exactly five columns");

const REPORTS = [
  { id: "DP", key: "D", value: "daily_project", title: "PesoWise Daily Project" },
  { id: "DE", key: "E", value: "detailed_expense", title: "PesoWise Detailed Expense" },
  { id: "CV", key: "V", value: "claim_verification", title: "PesoWise Claim Verification" },
  { id: "CA", key: "A", value: "claim_approval", title: "PesoWise Claim Approval" },
];

// token index in PWTCELLS, width (% of page, sums to 98), alignment
const COLS = [
  { head: FIVE_COLUMNS[0], tok: 2, w: 14, align: "Left" },
  { head: FIVE_COLUMNS[1], tok: 3, w: 27, align: "Left" },
  { head: FIVE_COLUMNS[2], tok: 4, w: 33, align: "Left" },
  { head: FIVE_COLUMNS[3], tok: 5, w: 12, align: "Left" },
  { head: FIVE_COLUMNS[4], tok: 6, w: 12, align: "Right" },
];

const q = (s) => `"${String(s).replace(/"/g, "'")}"`;
const out = [];
const L = (...x) => out.push(...x);
const F = "Use : Short Name Field";

L(
  ";; PesoWise -> TallyPrime reports (pwt). GENERATED by connector/pwtally/scripts/gen-tdl.mjs - do not edit by hand.",
  ";; Read-only. Rows are aggregated five-column results synchronised from PesoWise (ledgers in group 'PesoWise Report Data').",
  "",
  "[System : UDF]",
  "PWTREPORT : String : 26101", "PWTKEY : String : 26102", "PWTREV : String : 26103",
  "PWTJOB : String : 26104", "PWTCELLS : String : 26105",
  "",
  "[#Menu : Gateway of Tally]",
  "Add : Key Item : PesoWise Reports : W : Menu : PWT Reports Menu", "",
  "[Menu : PWT Reports Menu]", "Title : \"PesoWise Reports\"",
  ...REPORTS.map((r) => `Key Item : ${r.title.replace("PesoWise ", "")} : ${r.key} : Display : PWT ${r.id} List`),
  "",
  ";; Token n (1-based) of a pipe-delimited flat row. __PW_EMPTY__ marks blank cells.",
  "[Function : PWT Tok]", "Parameter : PWTFlat : String", "Parameter : PWTIdx : Number",
  "Variable : PWTRes : String", "Variable : PWTCnt : Number",
  "00 : SET : PWTRes : \"\"", "10 : SET : PWTCnt : 0",
  "20 : FOR TOKEN : PWTTokVal : ##PWTFlat : \"|\"",
  "30 : INCREMENT : PWTCnt",
  "40 : IF : ##PWTCnt = ##PWTIdx",
  "50 : IF : ##PWTTokVal = \"__PW_EMPTY__\"", "60 : SET : PWTRes : \"\"", "70 : ELSE", "80 : SET : PWTRes : ##PWTTokVal", "90 : END IF",
  "100 : END IF", "110 : END FOR", "120 : RETURN : ##PWTRes", "",
  "[Function : PWT Num]", "Parameter : PWTFlat : String", "Parameter : PWTIdx : Number", "Returns : Number", "Variable : PWTNumTmp : String",
  "00 : SET : PWTNumTmp : $$PWTTok:##PWTFlat:##PWTIdx", "10 : RETURN : $$Number:##PWTNumTmp", "",
  "[Style : PWT Head Style]", "Font : Arial Bold", "Height : 11", "",
  "[Style : PWT Title Style]", "Font : Arial Bold", "Height : 14", "",
  "[Style : PWT Row Style]", "Font : Arial", "Height : 11", "",
);

for (const r of REPORTS) {
  const P = `PWT ${r.id}`;
  const CN = `PWT${r.id}Rows`; // space-free (see header note)
  L(
    "[System : Formula]", `${P} Filt : $PWTREPORT = ${q(r.value)}`, "",
    `[Collection : ${CN}]`, "Type : Ledger", "Fetch : Name, PWTREPORT, PWTKEY, PWTREV, PWTCELLS", `Filter : ${P} Filt`,
    "Compute : PWTN7 : $$PWTNum:$PWTCELLS:7", "Sort : @@Default : $PWTCELLS", "",
    `[Report : ${P} List]`, "Use : DSP Template", `Form : ${P} List Form`, `Title : ${q(r.title)}`, "",
    `[Form : ${P} List Form]`, `Part : ${P} Head Part, ${P} Grid Part, ${P} Foot Part`, "Height : 100% Screen", "Width : 100% Screen", "",
    `[Part : ${P} Head Part]`, `Line : ${P} Co Line, ${P} Title Line, ${P} Sub Line`,
    `[Line : ${P} Co Line]`, `Field : ${P} Co Field`,
    `[Field : ${P} Co Field]`, F, "Set as : $$CurrentCompany", "Width : 98% Page", "Align : Centre", "Style : PWT Title Style", "Skip : Yes", "",
    `[Line : ${P} Title Line]`, `Field : ${P} Title Field`,
    `[Field : ${P} Title Field]`, F, `Set as : ${q(r.title)}`, "Width : 98% Page", "Align : Centre", "Style : PWT Head Style", "Skip : Yes", "",
    `[Line : ${P} Sub Line]`, `Field : ${P} Sub Label, ${P} Sub Count`,
    `[Field : ${P} Sub Label]`, F, `Set as : ${q("Aggregated rows synchronised from PesoWise:")}`, "Width : 30% Page", "Style : PWT Row Style", "Skip : Yes",
    `[Field : ${P} Sub Count]`, F, "Type : Number", `Set as : $$CollCount:${CN}`, "Width : 8% Page", "Style : PWT Head Style", "Skip : Yes", "",
    `[Part : ${P} Grid Part]`, `Line : ${P} Col Head Line, ${P} Data Line`, `Repeat : ${P} Data Line : ${CN}`,
    "Scroll : Vertical", "Common Border : Yes", "",
    `[Line : ${P} Col Head Line]`, `Field : ${COLS.map((_, i) => `${P} H${i + 1}`).join(", ")}`, "Border : Thin Box",
    `[Line : ${P} Data Line]`, `Field : ${COLS.map((_, i) => `${P} D${i + 1}`).join(", ")}`, "Border : Thin Bottom", "",
  );
  COLS.forEach((c, i) => {
    L(
      `[Field : ${P} H${i + 1}]`, F, `Set as : ${q(c.head)}`, `Width : ${c.w}% Page`, "Border : Thin Left", "Align : Centre", "Style : PWT Head Style", "Skip : Yes",
      `[Field : ${P} D${i + 1}]`, F, `Set as : $$PWTTok:$PWTCELLS:${c.tok}`, `Width : ${c.w}% Page`, "Border : Thin Left", `Align : ${c.align}`, "Style : PWT Row Style", "Skip : Yes", "",
    );
  });
  L(
    `[Part : ${P} Foot Part]`, `Line : ${P} Total Line`, "Border : Thin Box",
    `[Line : ${P} Total Line]`, `Field : ${COLS.map((_, i) => `${P} T${i + 1}`).join(", ")}`,
  );
  COLS.forEach((c, i) => {
    const set = i === 0 ? q("Grand Total") : i === 4 ? `$$CollNumTotal:${CN}:$PWTN7` : `""`;
    L(
      `[Field : ${P} T${i + 1}]`, F, ...(i === 4 ? ["Type : Number", "Format : \"Decimals:2\""] : []),
      `Set as : ${set}`, `Width : ${c.w}% Page`, "Border : Thin Left", `Align : ${c.align}`, "Style : PWT Head Style", "Skip : Yes",
    );
  });
  L("");
}

const dir = join(root, "tdl");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "PesoWise-Tally.tdl"), out.join("\n") + "\n");
console.log("Wrote", join(dir, "PesoWise-Tally.tdl"), `(${out.length} lines)`);
